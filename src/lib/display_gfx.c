static void set_address(uint8_t y){
  uint8_t x = 0;
  if(y >= GFX_HALF_HEIGHT){
    y -= GFX_HALF_HEIGHT;
    x = GFX_HALF_WORDS;
  }
  display_send_command(GFX_SET_ADDRESS | y);
  display_send_command(GFX_SET_ADDRESS | x);
}

static uint8_t glyph_index(uint8_t c){
  if(c >= GFX_FIRST_CHAR && c <= GFX_LAST_CHAR) return c - GFX_FIRST_CHAR;
  if(c >= DISPLAY_GFX_NEWLINE && c <= DISPLAY_GFX_LAST) return GFX_SPECIAL_INDEX + c - DISPLAY_GFX_NEWLINE;
  return GFX_SPECIAL_INDEX + DISPLAY_GFX_UNKNOWN - DISPLAY_GFX_NEWLINE;
}

// glyph of the unicode char: ASCII, cyrillic, else the unknown glyph
uint8_t display_gfx_glyph(uint16_t code){
  if(code >= GFX_FIRST_CHAR && code <= GFX_LAST_CHAR) return code;
  if(code >= UNICODE_CYRILLIC_A && code < UNICODE_CYRILLIC_A + DISPLAY_GFX_CYRILLIC_LETTERS){
    return DISPLAY_GFX_CYRILLIC + code - UNICODE_CYRILLIC_A;
  }
  if(code == UNICODE_CYRILLIC_YO_UPPER) return DISPLAY_GFX_YO_UPPER;
  if(code == UNICODE_CYRILLIC_YO_LOWER) return DISPLAY_GFX_YO_LOWER;
  return DISPLAY_GFX_UNKNOWN;
}

// graphics on, the text layer is cleared (it is shown over the graphics)
void display_gfx_on(void){
  display_send_command(GFX_BASIC_FUNCTION);
  display_clear();
  display_send_command(GFX_EXTENDED_FUNCTION);
  display_gfx_clear();
  display_send_command(GFX_GRAPHIC_ON);
}

// back to the text mode, the text layer is cleared
void display_gfx_off(void){
  display_send_command(GFX_EXTENDED_FUNCTION);
  display_send_command(GFX_BASIC_FUNCTION);
  display_clear();
}

void display_gfx_clear(void){
  for(uint8_t y = 0; y < DISPLAY_GFX_ROWS * DISPLAY_GFX_CELL_HEIGHT; y++){
    set_address(y);
    for(uint8_t i = 0; i < GFX_LINE_BYTES; i++){
      display_send_data(0);
    }
  }
}

// text row: len chars of text (the rest is empty), cell cursor is inverted,
// invert - the whole row is inverted
void display_gfx_row(uint8_t row, const char *text, uint8_t len, uint8_t cursor, uint8_t invert){
  uint8_t line[GFX_LINE_BYTES];

  for(uint8_t y = 0; y < DISPLAY_GFX_CELL_HEIGHT; y++){
    memset(line, invert ? 0xFF : 0x00, sizeof(line));
    for(uint8_t i = 0; i < DISPLAY_GFX_COLS; i++){
      uint8_t index = glyph_index(i < len ? (uint8_t)text[i] : ' ');
      for(uint8_t k = 0; k < DISPLAY_GFX_CELL_WIDTH; k++){
        uint8_t on = 0;
        if(k < GFX_FONT_WIDTH && y < GFX_FONT_HEIGHT){
          on = (pgm_read_byte(&font[index][k]) >> y) & 1;
        }
        if(i == cursor) on ^= 1;
        // XOR: pixels of inverted row become dark
        if(on){
          uint8_t x = i * DISPLAY_GFX_CELL_WIDTH + k;
          line[x >> 3] ^= 0x80 >> (x & 7);
        }
      }
    }
    set_address(row * DISPLAY_GFX_CELL_HEIGHT + y);
    for(uint8_t i = 0; i < GFX_LINE_BYTES; i++){
      display_send_data(line[i]);
    }
  }
}
